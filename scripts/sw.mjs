// Writes dist/sw.js: precaches every built file under a version derived from their content.
// A new deploy = a new version: the next launch installs it, the one after runs it.
// public/branded is 3,400 files: never precached, each one is kept the first time it is used.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const DIST = 'dist';

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(DIST)
  .filter((f) => !/sw\.js$|\.map$|OFL\.txt$/.test(f) && !/[\\/](pose|branded)[\\/]/.test(f))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(f));
const version = hash.digest('hex').slice(0, 12);
const urls = files.map((f) => './' + relative(DIST, f).replace(/\\/g, '/')).map((u) => (u === './index.html' ? './' : u));

const sw = `// Generated by scripts/sw.mjs
const V = 'bn-${Date.now()}-${version}';
const ASSETS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(V).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      // the previous version stays one more round: a page it served may still be open and need its files
      .then((ks) => ks.filter((k) => k.startsWith("bn-")).sort((a, b) => Number(b.split("-")[1]) - Number(a.split("-")[1])))
      .then((ks) => Promise.all(ks.slice(2).filter((k) => k !== V).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET') return;
  const url = new URL(r.url);
  if (url.origin !== location.origin) return;
  // 2026-11-16: the page from the network first, so a new deploy shows on the next opening; the cache only when
  // offline or slower than 3 s. And from THIS version's cache: caches.match() searched the older version first and
  // kept serving the old app (the user saw no update after closing it three times).
  if (r.mode === 'navigate') {
    e.respondWith((async () => {
      const cache = await caches.open(V);
      try {
        const res = await Promise.race([fetch(r, { cache: 'no-cache' }), new Promise((_, no) => setTimeout(() => no(new Error('slow')), 3000))]);
        if (res && res.ok) { cache.put('./', res.clone()); return res; }
      } catch (err) { /* offline or slow: the cached page */ }
      return (await cache.match('./')) || (await caches.match('./')) || fetch(r);
    })());
    return;
  }
  if (url.pathname.includes('/branded/')) {
    e.respondWith(caches.open('branded-data').then((c) => c.match(r).then((m) => m || fetch(r).then((res) => {
      if (res.ok) c.put(r, res.clone());
      return res;
    }))));
    return;
  }
  e.respondWith(caches.open(V).then((c) => c.match(r, { ignoreSearch: true })).then((m) => m || caches.match(r, { ignoreSearch: true })).then((m) => m || fetch(r)));
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files, version ${version}`);
